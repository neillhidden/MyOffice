  await page.locator('#home-shopping-subcategory').selectOption('Jogos');
  await page.locator('#home-shopping-quantity').fill('2');
  await page.locator('#home-shopping-price').fill('125');
  await page.locator('#home-shopping-save').click();
  await page.getByRole('button',{name:'Registar pagamento',exact:true}).click();
  await page.getByText('Pago',{exact:true}).waitFor();
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('myoffice-home-v1')));
  assert.equal(saved.entries.length,1);assert.equal(saved.entries[0].amount,250);assert.equal(saved.shopping[0].entryId,saved.entries[0].id);
  await page.reload();
  await page.locator('#home-nav-7').click();
  await page.getByText('Pago',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Registar pagamento',exact:true}).count(),0);
  await page.locator('#mode-btn-business').click();
  await page.locator('#app-sidebar').getByRole('button',{name:'Calendário',exact:true}).click();
  await page.locator('#calendar-period-label').waitFor();
  assert.match(await page.locator('#calendar-period-label').innerText(),/Outubro de 2026/);
  await page.locator('#calendar-prev-btn').click();
  assert.match(await page.locator('#calendar-period-label').innerText(),/Setembro/);
  await page.locator('#calendar-today-btn').click();
  assert.match(await page.locator('#calendar-period-label').innerText(),/Outubro/);
  await page.locator('#calendar-add-event-btn').click();
  assert.equal(await page.locator('#event-date-input').inputValue(),'2026-10-08');
  await page.locator('#btn-close-event-modal').click();
  await page.clock.setSystemTime(new Date('2026-10-09T12:00:00+01:00'));
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await page.waitForFunction(()=>document.querySelector('#calendar-day-2026-10-09 span')?.className.includes('bg-blue-600'));
  await page.locator('#calendar-add-event-btn').click();
  await page.waitForFunction(()=>document.querySelector('#event-date-input')?.value === '2026-10-09');
  assert.equal(await page.locator('#event-date-input').inputValue(),'2026-10-09');
  await page.locator('#btn-close-event-modal').click();
  await page.clock.setSystemTime(new Date('2027-01-31T12:00:00+01:00'));
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await page.locator('#calendar-today-btn').click();
  await page.locator('#calendar-next-btn').click();
  assert.match(await page.locator('#calendar-period-label').innerText(),/Fevereiro de 2027/);
  await page.locator('#calendar-prev-btn').click();
  assert.match(await page.locator('#calendar-period-label').innerText(),/Janeiro de 2027/);
